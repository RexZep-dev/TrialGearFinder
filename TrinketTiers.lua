-- Ранг аксессуара для основного списка: буква и её цвет. Спек: открытый
-- в окне «Сборки», а если оно закрыто - свой.
-- Цвета - как качество вещей, так же у Class Codex: S оранжевая,
-- A фиолетовая, B синяя, C зелёная.
local TIER_COLOR = { S = "ff8000", A = "a335ee", B = "0070dd", C = "1eff00" }
function ns.TrinketTier(itemID, classFilter)
    -- Открыто окно «Сборки» - спек из него, любого класса (пользователь
    -- 27 сентября: переключал там классы и спеки, а буквы не менялись).
    local builds = _G.TrialGearFinderBiSFrame
    local spec
    if builds and builds:IsShown() and ns.BuildsSpecID then
        spec = ns.BuildsSpecID
    else
        local idx = GetSpecialization and GetSpecialization()
        spec = idx and GetSpecializationInfo(idx)
    end
    local tier = spec and ns.TrinketTiers[spec] and ns.TrinketTiers[spec][itemID]
    if not tier then return nil end
    return tier, TIER_COLOR[tier]
end
